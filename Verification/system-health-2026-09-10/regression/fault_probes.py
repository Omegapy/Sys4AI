ROWS = []


def snapshot(root):
    return {str(p.relative_to(root)): [hashlib.sha256(p.read_bytes()).hexdigest(), p.stat().st_mtime_ns]
            for p in root.rglob("*") if p.is_file() and not p.is_symlink()}


def run(name, root, kind="ontology", command="health", note="", code=None):
    argv = [str(ROOT / ".venv/bin/python")]
    argv += ["-c", code, str(root)] if code else [str(ROOT / f".agents/skills/{kind}/scripts/{kind}.py"), "--project-root", str(root), command]
    before = snapshot(root)
    start = datetime.datetime.now(datetime.timezone.utc).isoformat()
    tick = time.monotonic()
    result = subprocess.run(argv, cwd=ROOT, env=ENV, capture_output=True)
    (OUT / f"probe-{name}.stdout.log").write_bytes(result.stdout)
    (OUT / f"probe-{name}.stderr.log").write_bytes(result.stderr)
    row = {"name": name, "note": note, "command": argv, "cwd": str(ROOT),
           "started_at": start, "duration_seconds": round(time.monotonic() - tick, 6),
           "exit_code": result.returncode, "fixture_bytes_and_mtimes_unchanged": before == snapshot(root),
           "stdout": f"probe-{name}.stdout.log", "stderr": f"probe-{name}.stderr.log",
           "result": json.loads(result.stdout)}
    ROWS.append(row)
    (OUT / f"probe-{name}.receipt.json").write_text(json.dumps({k: v for k, v in row.items() if k != "result"}, indent=2) + "\n")


